#!/usr/bin/env python3
"""Bundle results/measurements.json (+ test file names, template, line counts) into site/data.js and print/data.js."""
import json, re, pathlib
R = pathlib.Path(__file__).parent
m = json.loads((R / 'results/measurements.json').read_text())
owner = {}
for f in sorted((R / 'test').glob('*.test.js')):
    src = f.read_text()
    for name in re.findall(r"^test\('((?:[^'\\]|\\.)*)'", src, re.M): owner[name.replace("\\'", "'")] = f.name
    for name in re.findall(r"^  test\(`([^`]*)`", src, re.M): owner[name] = f.name
for t in m['tests']:
    t['file'] = owner.get(t['name']) or next((v for k, v in owner.items() if '${' in k and t['name'].startswith(k.split('${')[0])), '?')
files = [{'file': str(p.relative_to(R)), 'lines': p.read_text().count('\n') + 1} for p in sorted([*R.glob('src/**/*.js'), *R.glob('fake/*.js'), *R.glob('test/**/*.js'), *R.glob('bench/*.js'), *R.glob('config/*'), *R.glob('ghl/*')])]
data = {'m': m, 'template': json.loads((R / 'ghl/custom-webhook-body.json').read_text()), 'firm': json.loads((R / 'config/firm.json').read_text()), 'files': files}
js = '// generated by build.py from results/ - do not edit\nwindow.DATA = ' + json.dumps(data) + ';\n'
for d in ('site', 'print'):
    (R / d).mkdir(exist_ok=True); (R / d / 'data.js').write_text(js)
print(f"tests {sum(t['ok'] for t in m['tests'])}/{len(m['tests'])}, unmapped {[t['name'] for t in m['tests'] if t['file'] == '?']}, {len(js)//1024} KB")
